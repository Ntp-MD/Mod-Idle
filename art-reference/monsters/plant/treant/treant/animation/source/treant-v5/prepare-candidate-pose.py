from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[4]
ANIMATION = ROOT / 'art-reference/monsters/plant/treant/treant/animation'
OUTPUTS = ROOT / 'art-reference/animation/outputs/treant-v5'
DIRECTIONS = {'south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west'}
ACTIONS = {'walk', 'attack', 'hit', 'death'}
DEFAULT_HEIGHT = {'walk': 163, 'attack': 162, 'hit': 160}
DEATH_HEIGHT = {'00-fall': 137, '01-collapse': 120, '02-ground': 97, '03-settle': 82}


def main() -> None:
    parser = argparse.ArgumentParser(description='Normalize one Treant imagegen pose to an unapproved canonical source slot.')
    parser.add_argument('--source', required=True, help='one-pose PNG source, generated by image_gen or an existing draft')
    parser.add_argument('--action', required=True, choices=sorted(ACTIONS))
    parser.add_argument('--direction', required=True, choices=sorted(DIRECTIONS))
    parser.add_argument('--phase', required=True)
    parser.add_argument('--source-label', help='project-relative provenance path if the source is already in the workspace')
    parser.add_argument('--target-height', type=int, help='override the matching baseline subject height')
    args = parser.parse_args()

    source = Path(args.source).resolve()
    if not source.is_file():
        parser.error(f'source image does not exist: {source}')
    with Image.open(source) as opened:
        original = opened.convert('RGBA')
    alpha = original.getchannel('A')
    bounds = alpha.point(lambda value: 255 if value >= 8 else 0).getbbox()
    if bounds is None:
        parser.error('source has no visible pose pixels')
    sprite = original.crop(bounds)

    raw_name = f'{args.action}-{args.direction}-{args.phase}-v1.png'
    raw_path = OUTPUTS / raw_name
    raw_path.parent.mkdir(parents=True, exist_ok=True)
    if source != raw_path.resolve():
        shutil.copy2(source, raw_path)
    source_label = args.source_label
    if source_label is None:
        source_label = raw_path.relative_to(ROOT).as_posix()

    target_height = args.target_height
    if target_height is None:
        target_height = DEATH_HEIGHT.get(args.phase, 137) if args.action == 'death' else DEFAULT_HEIGHT[args.action]
    scale = target_height / sprite.height
    resized_size = (max(1, round(sprite.width * scale)), target_height)
    sprite = sprite.resize(resized_size, Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (384, 384), (0, 0, 0, 0))
    x = (384 - sprite.width) // 2
    y = 288 - sprite.height
    if x < 0 or y < 0:
        parser.error(f'normalized pose exceeds the 384x384 canvas: {resized_size}')
    canvas.alpha_composite(sprite, (x, y))

    relative = Path('poses') / args.action / args.direction / f'{args.phase}.png'
    output = ANIMATION / relative
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        parser.error(f'canonical slot already exists; refusing to overwrite: {relative.as_posix()}')
    canvas.save(output)
    metadata = {
        'status': 'candidate-review-required',
        'generator': 'built-in image_gen',
        'source': source_label,
        'sourceCanvas': {'width': original.width, 'height': original.height},
        'sourceAlphaBoundsThreshold': 8,
        'sourceAlphaBounds': list(bounds),
        'action': args.action,
        'direction': args.direction,
        'phase': args.phase,
        'processing': {
            'method': 'single-pose alpha-bounds crop; proportional resize to existing Treant source scale; centered on 384x384 canvas at anchor',
            'targetSubjectHeight': target_height,
            'targetSize': list(resized_size),
            'lowAlphaOutsideCrop': 'pixels below alpha 8 excluded from crop bounds'
        },
        'canvas': {'width': 384, 'height': 384},
        'anchor': {'x': 192, 'y': 288},
        'visualReview': {'identityAccepted': False, 'exactAngleAccepted': False, 'sequenceAccepted': False},
        'qa': {'atlas': False, 'anchor': False}
    }
    metadata_path = output.with_suffix('.meta.json')
    metadata_path.write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'pose': relative.as_posix(), 'source': source_label, 'sourceBounds': list(bounds), 'canvas': list(canvas.size), 'subjectSize': list(resized_size), 'status': metadata['status']}))


if __name__ == '__main__':
    main()