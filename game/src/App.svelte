  /** Spend or refund stat points. Takes effect on the next tick, so the sheet works mid-combat. */
  function allocate(k: StatKey, delta: number) {
    const p = gameState.player;
    if (delta > 0) {
      const n = Math.min(delta, p.statPoints);
      if (n <= 0) return;
