export function skillFxFor(id: string | undefined) {
  const definition = id ? skillFxDefinitions[id] : undefined;
  if (!definition) return undefined;
  const asset = definition.asset ? sharedAssets[definition.asset] : undefined;
  return {
    ...definition,
    path: asset ? composeAsset(asset.impact) : paths[definition.shape],
    projectilePath: asset ? composeAsset(asset.projectile) : paths[definition.shape],
    posePath: asset ? composeAsset(asset.pose) : paths[definition.shape],
  };
}

